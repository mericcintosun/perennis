/**
 * The window queue the plan builder writes into the vault.
 *
 * A thin wrapper over discoverEventWindows() in lib/markets.ts, which owns the
 * three level fallback: the sponsor SDK first, then the per id getMarket read
 * that used to live in this function, then the fixtures. Each level that does
 * not answer attaches a note written by us, so a fixture list never renders
 * under a chain badge without saying why.
 *
 * This function keeps its name and its return shape because both adapters, both
 * API routes and DEMO.md step 2 are written against them.
 */
export async function fetchEventWindows(): Promise<ApiResponse<EventWindow[]>> {
  const { response } = await discoverEventWindows();
  return response;
}

/**
 * The roll ledger, read back from RollSettled logs on the deployed vault.
 *
 * This is the mechanism Phase 2 took off fixtures. Every row carries a real
 * transaction hash and a real block number, so DEMO.md step 5 can open the row
 * on the Shannon explorer.
 *
 * Bounded on purpose, at three separate points:
 *   - fromBlock is latest minus LEDGER_LOOKBACK_BLOCKS, never block zero, so a
 *     provider that refuses an unbounded range still answers
 *   - at most MAX_LEDGER_ROWS logs are kept, the most recent ones
 *   - the per row follow up reads run only over those kept logs
 * There is no unbounded loop anywhere on this path.
 *
 * `trigger` is derived, not assumed: the sender of the transaction that emitted
 * the log is compared against owner() on the vault. A sender that is not the
 * owner means the roll was produced by the validator synthetic call in the
 * settlement block, which is exactly the claim the demo makes on camera.
 */
export async function fetchRollLedger(
  decimalsHint?: number
): Promise<ApiResponse<RollEntry[]>> {
  const seedLedger = vaults[1].ledger;

  if (!VAULT_ADDRESS) {
    return {
      source: "seed",
      data: seedLedger,
      note: failureNote(
        coreFailure(
          "not-configured",
          "No vault address is set, so the roll ledger comes from the fixtures."
        )
      ),
    };
  }

  try {
    const client = publicClient();
    const address = VAULT_ADDRESS;

    const latest = await withTimeoutAndRetry(() => client.getBlockNumber());
    const fromBlock =
      latest > LEDGER_LOOKBACK_BLOCKS ? latest - LEDGER_LOOKBACK_BLOCKS : 0n;

    const logs = await withTimeoutAndRetry(() =>
      client.getLogs({
        address,
        event: rollSettledEvent,
        fromBlock,
        toBlock: "latest",
      })
    );

    // Most recent rows only. Everything after this point iterates a list whose
    // length is capped by MAX_LEDGER_ROWS.
    const recent = logs
      .filter((log) => log.transactionHash !== null)
      .slice(-MAX_LEDGER_ROWS);

    logCore("ledger logs read", {
      rows: recent.length,
      lookback: LEDGER_LOOKBACK_BLOCKS.toString(),
    });

    if (recent.length === 0) {
      return {
        source: "chain",
        data: [],
        note: "No RollSettled logs in the lookback window yet. The first row lands when the open window settles.",
      };
    }

    const decimals = decimalsHint ?? (await fetchCollateralDecimals());
    const scale = 10 ** decimals;

    const ownerAddress = await withTimeoutAndRetry(() =>
      client.readContract({ address, abi: perennisVaultAbi, functionName: "owner" })
    ).catch(() => null);

    const senders = await senderByTxHash(recent.map((log) => log.transactionHash!));

    const details = await Promise.allSettled(
      recent.map((log) =>
        withTimeoutAndRetry(() =>
          client.readContract({
            address,
            abi: perennisVaultAbi,
            functionName: "rollAt",
            args: [log.args.index ?? 0n],
          })
        )
      )
    );

    const data: RollEntry[] = recent.map((log, i): RollEntry => {
      const detail = details[i];
      const roll = detail.status === "fulfilled" ? detail.value : null;

      const marketId = (log.args.marketId ?? ZERO_BYTES32) as string;
      const stake = roll ? Number(roll.stake) / scale : 0;
      const payout = Number(log.args.payout ?? 0n) / scale;
      const direction: Direction =
        roll && Number(roll.direction) === 1 ? "DOWN" : "UP";
      const won = Boolean(log.args.won);

      const sender = senders.get(log.transactionHash!.toLowerCase()) ?? null;
      // No owner read and no sender read means we cannot prove who sent it, so
      // the row is labelled manual rather than claiming a validator call.
      const isOwnerCall =
        ownerAddress !== null &&
        sender !== null &&
        sender === ownerAddress.toLowerCase();

      return {
        index: Number(log.args.index ?? 0n) + 1,
        marketId,
        asset: assetForMarket(marketId),
        direction,
        entryCents: entryCentsFrom(marketId, direction, stake, payout, won),
        stake: round2(stake),
        // The event carries a boolean, not a three way outcome, so a voided
        // market reads as LOST here until the markets module exposes the
        // settlement mode. Recorded in HANDOFF.md as a known gap.
        outcome: won ? "WON" : "LOST",
        payout: round2(payout),
        balanceAfter: round2(Number(log.args.balanceAfter ?? 0n) / scale),
        settledAt: roll
          ? new Date(Number(roll.settledAt) * 1000).toISOString()
          : new Date(0).toISOString(),
        blockNumber: Number(log.blockNumber ?? 0n),
        txHash: log.transactionHash!,
        trigger: isOwnerCall ? "manual" : "reactivity",
      };
    });

    return { source: "chain", data };
  } catch (error) {
    return seedFallback(seedLedger, "ledger logs read", error);
  }
}

/**
 * One transaction read per unique hash, so twelve ledger rows produced by three
 * transactions cost three calls and not twelve. Returns lowercased senders keyed
 * by lowercased hash.
 */
async function senderByTxHash(
  hashes: readonly `0x${string}`[]
): Promise<Map<string, string>> {
  const client = publicClient();
  const unique = Array.from(new Set(hashes.map((h) => h.toLowerCase())));

  const results = await Promise.allSettled(
    unique.map((hash) =>
      withTimeoutAndRetry(() =>
        client.getTransaction({ hash: hash as `0x${string}` })
      )
    )
  );

  const map = new Map<string, string>();
  results.forEach((result, i) => {
    if (result.status === "fulfilled" && result.value.from) {
      map.set(unique[i], result.value.from.toLowerCase());
    }
  });
  return map;
}

/**
 * Vault state. Chain path reads the deployed PerennisVault; the ABI above is
 * generated from the contract in this repo, so this call is the real thing.
 * The ledger is no longer seeded when the chain path works: fetchRollLedger()
 * supplies it, and the fixture ledger is only the fallback.
 */
export async function fetchVaults(): Promise<ApiResponse<Vault[]>> {
  if (!VAULT_ADDRESS) {
    return {
      source: "seed",
      data: vaults,
      note: failureNote(
        coreFailure(
          "not-configured",
          "No vault address is set, so the console is on seed data."
        )
      ),
    };
  }

  try {
    const client = publicClient();
    const address = VAULT_ADDRESS;

    const [snapshot, planRow] = await Promise.all([
      withTimeoutAndRetry(() =>
        client.readContract({
          address,
          abi: perennisVaultAbi,
          functionName: "snapshot",
        })
      ),
      withTimeoutAndRetry(() =>
        client.readContract({
          address,
          abi: perennisVaultAbi,
          functionName: "plan",
        })
      ),
    ]);

    const decimals = await fetchCollateralDecimals();
    const scale = 10 ** decimals;

    const [
      balance,
      status,
      stopReason,
      windowsFilled,
      consecutiveLosses,
      openMarketId,
      queueLength,
      subscriptionId,
    ] = snapshot;
    const [
      direction,
      stakePerWindow,
      planWindows,
      maxConsecutiveLosses,
      floorBalance,
      takeProfit,
    ] = planRow;

    logCore("vault snapshot read", {
      windowsFilled: Number(windowsFilled),
      queue: Number(queueLength),
    });

    // The ledger comes off RollSettled logs. If that read falls back to seed
    // the note travels with it, so the console never shows a fixture ledger
    // under a chain badge without saying so.
    const ledger = await fetchRollLedger(decimals);

    const live: Vault = {
      ...vaults[1],
      id: "vault-live",
      address,
      label: "Live vault",
      balance: Number(balance) / scale,
      status: (["IDLE", "ACTIVE", "STOPPED", "COMPLETED"] as const)[
        Number(status)
      ],
      stopReason: (
        [
          null,
          "consecutive-losses",
          "floor-balance",
          "take-profit",
          "plan-complete",
          "owner-halt",
        ] as const
      )[Number(stopReason)],
      windowsFilled: Number(windowsFilled),
      consecutiveLosses: Number(consecutiveLosses),
      openMarketId: openMarketId === ZERO_BYTES32 ? null : openMarketId,
      queue: new Array(Number(queueLength)).fill(""),
      plan: {
        asset: "BTC",
        direction: Number(direction) === 0 ? "UP" : "DOWN",
        stakePerWindow: Number(stakePerWindow) / scale,
        windows: Number(planWindows),
        rules: {
          maxConsecutiveLosses: Number(maxConsecutiveLosses),
          floorBalance: Number(floorBalance) / scale,
          takeProfit: Number(takeProfit) / scale,
        },
      } satisfies Plan,
      subscription: {
        ...vaults[1].subscription,
        subscriptionId: Number(subscriptionId),
      },
      ledger: ledger.data,
    };

    return {
      source: "chain",
      data: [vaults[0], live, vaults[2]],
      ...(ledger.source === "seed" && ledger.note
        ? { note: ledger.note }
        : {}),
    };
  } catch (error) {
    return seedFallback(vaults, "vault snapshot read", error);
  }
}

/**
 * Collateral decimals are read from the token, never assumed. tUSDC on Shannon
 * is 6 decimals but the mainnet USDso deployment does not have to match.
 */
export async function fetchCollateralDecimals(): Promise<number> {
  if (!COLLATERAL_TOKEN) return 6;
  try {
    const token = COLLATERAL_TOKEN;
    const decimals = await withTimeoutAndRetry(() =>
      publicClient().readContract({
        address: token,
        abi: erc20Abi,
        functionName: "decimals",
      })
    );
    logCore("decimals read", { decimals: Number(decimals) });
    return Number(decimals);
  } catch {
    logCore("chain read failed", { step: "decimals read", code: "upstream-error" });
    return 6;
  }
}

