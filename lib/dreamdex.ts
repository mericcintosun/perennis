/**
 * The one failure shape. Logs a single line carrying the step name and the error
 * code, never the provider message and never the error object, then hands back
 * the fixtures with a hint written by us.
 */
function seedFallback<T>(data: T, step: string, error: unknown): ApiResponse<T> {
  const code = classify(error);
  logCore("chain read failed", { step, code });

  const hint =
    code === "upstream-timeout"
      ? "The Shannon RPC did not answer in time, so this screen fell back to seed data."
      : "The Shannon RPC rejected the read, so this screen fell back to seed data.";

  return { source: "seed", data, note: failureNote(coreFailure(code, hint)) };
}

// toBytes32() is defined in lib/markets.ts now, next to the per id read that
// needs it, and is re-exported at the top of this file. It still serves the
// fallback path: fixture ids are the shortened form the DreamDEX UI displays and
// have to be right padded, while ids arriving full length from the SDK are
// already 64 hex characters and pass through unchanged.

/** The fixture window a chain market id corresponds to, when there is one. */
function windowFor(marketId: string): EventWindow | undefined {
  const target = marketId.toLowerCase();
  return eventWindows.find((w) => toBytes32(w.marketId).toLowerCase() === target);
}

function assetForMarket(marketId: string): Asset {
  return windowFor(marketId)?.asset ?? "BTC";
}

/**
 * The entry price is not in the RollSettled payload. Two ways to recover it,
 * in order of confidence:
 *   1. a winning roll pays 1 per contract, so stake divided by payout is the
 *      price actually paid
 *   2. otherwise fall back to the book price on the matching window
 * A losing roll on an unknown market leaves 0, which the console renders as 0c
 * rather than inventing a number.
 */
function entryCentsFrom(
  marketId: string,
  direction: Direction,
  stake: number,
  payout: number,
  won: boolean
): number {
  if (won && payout > 0 && stake > 0) {
    return Math.round((stake / payout) * 100);
  }
  const window = windowFor(marketId);
  if (!window) return 0;
  return direction === "UP" ? window.upAskCents : window.downAskCents;
}

function round2(n: number) {
  return Math.round(n * 100) / 100;
}
